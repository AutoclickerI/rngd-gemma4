#!/usr/bin/env python3
"""Compile an exact set of device kernel launches before linking the server."""

import argparse
import math
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile
import time

from patch_registry import decode, section


ROOT = Path(__file__).resolve().parents[2]
CRATE = "furiosa_opt_gemma4"
MARK = "# --- shard_build.py: temporary shard bins (removed on exit) ---"

# The device macros infer generic axes from the launch argument tuple. Expand
# the registry's numeric arguments into the same types used by the server.
GENERIC = {
    "ops_media::put_rows": ("&HbmTensor<bf16, Chip, m![Tok1024, H]>", "&HbmTensor<i32, Chip, m![PutRows]>", "&mut HbmTensor<bf16, Chip, m![T, H]>"),
    "ops_media::put_rows_at": ("&HbmTensor<bf16, Chip, m![Tok1024, H]>", "&HbmTensor<i32, Chip, m![PutRows]>", "&HbmTensor<i32, Chip, m![PutRows]>", "&mut HbmTensor<bf16, Chip, m![T, H]>"),
    "ops_media::put_pool_rows": ("&HbmTensor<bf16, Chip, m![MediaPool, H]>", "&HbmTensor<i32, Chip, m![PutRows]>", "&HbmTensor<i32, Chip, m![PutRows]>", "&mut HbmTensor<bf16, Chip, m![T, H]>"),
}


def read_table(path):
    rows = []
    seen = set()
    for line in Path(path).read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = line.split("\t")
        name = fields[0].removeprefix(CRATE + "::")
        if (len(fields) not in (2, 3) or (len(fields) == 3 and fields[2] != "serial")
                or not re.fullmatch(r"\w+(?:::\w+)+(?:\[\d+(?:,\d+)*\])?", name)):
            raise ValueError(f"{path}: malformed shard row {line!r}")
        seconds = float(fields[1])
        if name in seen or not math.isfinite(seconds) or seconds <= 0:
            raise ValueError(f"{path}: invalid estimate or duplicate row {name}")
        seen.add(name)
        rows.append((name, seconds, len(fields) == 3))
    return rows


def partition(rows, count):
    shards = [[0.0, []] for _ in range(count)]
    for name, seconds in sorted(rows, key=lambda row: -row[1]):
        shard = min(shards, key=lambda s: s[0])
        shard[0] += seconds
        shard[1].append(name)
    return [shard for shard in shards if shard[1]]


def launch_source(row):
    path, bracket, args = row.removeprefix(CRATE + "::").partition("[")
    prefix = f"            let _ = launch({CRATE}::{path}, "
    if not bracket:
        return prefix + "any()).await;"
    sizes = [int(arg) for arg in args.rstrip("]").split(",")]
    pack = re.fullmatch(r"ops_l0table::serve::pack_t(128|512|1024|1536)", path)
    if pack:
        dst = f"Tok{pack[1]}"
        types = ("&HbmTensor<bf16, Chip, m![T, H]>", f"&HbmTensor<i32, Chip, m![{dst}]>",
                 f"&mut HbmTensor<bf16, Chip, m![{dst}, H]>")
    else:
        types = GENERIC.get(path)
    if types is None or len(sizes) != 1:
        raise ValueError(f"shard row {row}: no launch argument types for this specialization")
    params = re.sub(r"\bT\b", f"Tok{sizes[0]}", ", ".join(types))
    return prefix + f"any::<(&mut Device, {params})>()).await;"


def shard_source(paths):
    calls = "\n".join(map(launch_source, paths))
    return f"""//! Generated by shard_build.py. These launches are only used at compile time.
#![allow(unused)]
use furiosa_opt_std::prelude::*;
use furiosa_opt_gemma4::{{Chip, axes::*, ops_media::PutRows}};
#[inline(never)]
fn any<T>() -> T {{ panic!("shard binaries never run") }}
fn main() {{
    if std::hint::black_box(false) {{
        tokio::runtime::Builder::new_current_thread().build().unwrap().block_on(async {{
{calls}
        }});
    }}
}}
"""


def src_hash():
    """Compute the source stamp used by opt_build.sh."""
    cmd = ("find src Cargo.toml Cargo.lock -type f -print0 "
           "| LC_ALL=C sort -z | xargs -0 sha256sum | sha256sum | cut -c1-16")
    return subprocess.run(["bash", "-c", cmd], capture_output=True, text=True, check=True).stdout.strip()


def run(cmd, log):
    start = time.monotonic()
    with log.open("w") as stream:
        status = subprocess.run(cmd, stdout=stream, stderr=subprocess.STDOUT).returncode
    return status, time.monotonic() - start, log.read_text(errors="replace")


def registry_rows(binary):
    try:
        elf = binary.read_bytes()
        off, size = section(elf)
        rows, _ = decode(elf[off:off + size])
    except (OSError, KeyError, AssertionError) as error:
        raise ValueError(f"{binary}: cannot read the Opt kernel registry: {error}") from error
    return {path.removeprefix(CRATE + "::") + ("[" + ",".join(map(str, key)) + "]" if key else "")
            for path, key, _ in rows}


def compare_registry(label, expected, actual):
    errors = []
    for message, rows in (("missing registry rows", expected - actual),
                          ("unexpected registry rows", actual - expected)):
        if rows:
            errors.append(f"{message}: {', '.join(sorted(rows))}")
    if errors:
        raise ValueError(f"{label}: " + "\n".join(errors))


def final_binary(flags, target):
    bins = [flag[6:] for flag in flags if flag.startswith("--bin=")]
    bins += [value for flag, value in zip(flags, flags[1:]) if flag == "--bin"]
    if len(bins) != 1 or any(flag in ("--bins", "--lib", "--examples") or flag.startswith(("--example", "--profile"))
                             for flag in flags):
        raise ValueError("shard_build.py requires one --bin target and the default debug or release profile")
    return target / ("release" if "--release" in flags else "debug") / bins[0]


def compiled(text):
    return re.findall(rf"^\s*Compiling {CRATE}::(\S+)\s*$", text, re.M)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--shards", type=int, default=0, help="default: min(16, CPUs in the affinity mask)")
    ap.add_argument("--table", type=Path, default=ROOT / "tools/native/shards/server.tsv")
    ap.add_argument("--logs", type=Path, help="default: $FURIOSA_OPT_OUT_DIR.shardlogs")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("final", nargs=argparse.REMAINDER)
    args = ap.parse_args()

    out = os.environ.get("FURIOSA_OPT_OUT_DIR")
    target = os.environ.get("CARGO_TARGET_DIR")
    if not out or not target:
        raise ValueError("set FURIOSA_OPT_OUT_DIR and CARGO_TARGET_DIR")
    manifest = Path("Cargo.toml")
    if not manifest.is_file() or not Path("src/lib.rs").is_file():
        raise ValueError("run in the crate root")
    flags = args.final[1:] if args.final[:1] == ["--"] else args.final
    flags = flags or ["--release", "--offline", "--locked", "--bin", "server"]
    binary = final_binary(flags, Path(target))
    base = [flag for prev, flag in zip([""] + flags, flags)
            if prev != "--bin" and flag != "--bin" and not flag.startswith("--bin=")]
    count = args.shards or min(16, len(os.sched_getaffinity(0)))
    if count < 1:
        raise ValueError("--shards must be positive")
    os.environ.setdefault("CARGO_BUILD_JOBS", str(count))

    rows = read_table(args.table)
    parallel = {name for name, _, serial in rows if not serial}
    shards = partition([(name, seconds) for name, seconds, serial in rows if not serial], count)
    if not shards:
        raise ValueError(f"{args.table}: no parallel launches")
    logs = (args.logs or Path(f"{out}.shardlogs")).resolve()
    print(f"shard_build: {len(parallel)} parallel kernels, {len(shards)} shards, "
          f"est. phase-1 kernel wall {max(s[0] for s in shards):.0f} s; logs {logs}", flush=True)
    if args.dry_run:
        for i, (seconds, paths) in enumerate(shards):
            print(f"  kshard_{i:02d} {seconds:6.1f} s {len(paths)} kernels")
        return 0

    original = manifest.read_bytes()
    if MARK.encode() in original:
        raise ValueError("Cargo.toml already holds temporary shard bins")
    logs.mkdir(parents=True, exist_ok=True)
    for stale in logs.glob("phase*.log"):
        stale.unlink()
    opt = str(ROOT / "tools/native/opt_build.sh")
    phase1 = logs / "phase1.log"
    with tempfile.TemporaryDirectory(dir=logs, prefix="shards.") as work:
        entries, names, launches = [], [], {}
        for i, (_, paths) in enumerate(shards):
            name = f"kshard_{i:02d}"
            file = Path(work) / (name + ".rs")
            source = shard_source(paths)
            file.write_text(source)
            lines = [line for line, text in enumerate(source.splitlines(), 1) if "let _ = launch(" in text]
            launches[file.name] = dict(zip(lines, paths, strict=True))
            entries.append(f'\n[[bin]]\nname = "{name}"\npath = "{file}"\n')
            names.extend(("--bin", name))
        manifest.write_bytes(original + ("\n" + MARK + "".join(entries)).encode())
        try:
            status, wall, text = run([opt, *base, "-j", str(len(shards)), "--keep-going", *names], phase1)
        finally:
            manifest.write_bytes(original)
        if status:
            errors = {launches[file][int(line)] for file, line in
                      re.findall(r"^\s*--> .*?(kshard_\d+\.rs):(\d+):\d+", text, re.M)
                      if int(line) in launches.get(file, {})}
            detail = f" at {', '.join(sorted(errors))}" if errors else ""
            raise ValueError(f"{args.table}: shard build failed{detail}. See {phase1}")
        shard_rows = set().union(*(registry_rows(binary.with_name(name)) for name in names[1::2]))
        compare_registry(str(args.table) + " phase 1", parallel, shard_rows)
    (Path(target) / ".opt-build-src").write_text(src_hash() + "\n")
    print(f"phase 1: {wall:.0f} s, {len(compiled(text))} compiled, {len(shard_rows)} registry rows", flush=True)

    phase2 = logs / "phase2.log"
    status, wall, text = run([opt, *flags], phase2)
    if status:
        raise ValueError(f"final build failed. See {phase2}")
    got = compiled(text)
    print(f"phase 2: {wall:.0f} s, {len(got)} compiled" + (f" ({', '.join(got)})" if got else ""))
    final = registry_rows(binary)
    compare_registry(str(args.table) + " final", {name for name, _, _ in rows}, final)
    repeated = set(got) & {name.partition("[")[0] for name in parallel}
    if repeated:
        raise ValueError(f"{args.table}: final build recompiled shard kernels: {', '.join(sorted(repeated))}")
    print(f"registry check: {len(shard_rows)} shard rows, {len(final - shard_rows)} final-only rows, "
          f"{len(final)} total")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ValueError as error:
        sys.exit(str(error))
